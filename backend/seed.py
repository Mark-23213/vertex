def _duration_for(alt):
    if alt >= 8000:
        return 42 + alt % 12
    if alt >= 7000:
        return 21 + alt % 8
    if alt >= 6000:
        return 16 + alt % 6
    if alt >= 5000:
        return 9 + alt % 4
    return 7 + alt % 3


def _price_for(alt):
    if alt >= 8000:
        base = 18000 + (alt - 8000) * 18
    elif alt >= 7000:
        base = 6000 + (alt - 7000) * 6
    elif alt >= 6000:
        base = 4000 + (alt - 6000) * 5
    elif alt >= 5000:
        base = 1800 + (alt - 5000) * 3
    else:
        base = max(900, 1000 + (alt - 3000))
    return int(round(base / 100.0)) * 100


def _success_for(alt):
    if alt >= 8000:
        return 42
    if alt >= 7500:
        return 38
    if alt >= 7000:
        return 50
    if alt >= 6000:
        return 64
    if alt >= 5000:
        return 80
    return 88


def _rating_for(alt):
    return round(4.6 + (alt / 8848) * 0.4, 1)


def _summary_for(name, alt, region, diff):
    if alt >= 8000:
        return f"Восьмитысячник {alt} м — серьёзная экспедиция в регионе {region} для опытных высотников."
    if alt >= 7000:
        return f"Семитысячник {alt} м в регионе {region} — высотная экспедиция с акклиматизацией и штурмовыми лагерями."
    if alt >= 6000:
        return f"Шеститысячник {alt} м — высотное восхождение в регионе {region}."
    if alt >= 5000:
        return f"Высотное восхождение {alt} м в регионе {region}."
    return f"Классическое восхождение {alt} м в регионе {region}."


def _itinerary_for(alt, dur):
    acc = max(3, dur // 3)
