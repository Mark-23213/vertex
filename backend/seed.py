def seed_expeditions() -> None:
    """Добавляет недостающие экспедиции (идемпотентно)."""
    db = SessionLocal()
    try:
        existing = {row[0] for row in db.query(Expedition.id).all()}
        added = 0
        for data in ALL_EXPEDITIONS:
            if data["id"] in existing:
                continue
            db.add(Expedition(**data))
            added += 1
        if added:
            db.commit()
            print(f"Добавлено экспедиций: {added}. Всего в каталоге: {len(ALL_EXPEDITIONS)}")
        else:
            print(f"Новых экспедиций нет. Всего: {len(ALL_EXPEDITIONS)}")
    finally:
        db.close()
